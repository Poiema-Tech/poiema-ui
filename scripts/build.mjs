#!/usr/bin/env node
// Zero-dependency build: src/tokens.json + src/css + src/js  ->  dist/, docs/tokens.md,
// contrast table in docs/color.md, skill references and llms-full.txt.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => join(root, ...p);
const read = (p) => readFileSync(r(p), 'utf8');
const write = (p, s) => { mkdirSync(dirname(r(p)), { recursive: true }); writeFileSync(r(p), s); };

const pkg = JSON.parse(read('package.json'));
const T = JSON.parse(read('src/tokens.json'));
const P = T.prefix;
const banner = `/*! ${pkg.name} v${pkg.version} — © Poiema, proprietary: Poiema use only (see LICENSE). Generated by scripts/build.mjs, do not edit. */\n`;

// ---------- helpers ----------
const entries = (group) => Object.entries(group).filter(([k]) => !k.startsWith('$'));
const val = (v) => (v && typeof v === 'object' && 'value' in v ? v.value : v);
const desc = (v) => (v && typeof v === 'object' ? v.description || '' : '');
const refCss = (s) => String(s).replace(/\{([\w-]+)\}/g, (_, n) => `var(--${P}-${n})`);
const refRaw = (s) => String(s).replace(/\{([\w-]+)\}/g, (_, n) => {
  if (!(n in T.primitives)) throw new Error(`Unknown primitive {${n}}`);
  return T.primitives[n];
});

// groups whose names are dropped from the variable (e.g. --pm-container, --pm-ease)
const FLAT = new Set(['layout', 'motion']);
const SCALES = ['font', 'text', 'weight', 'tracking', 'leading', 'radius', 'space', 'layout', 'shadow', 'motion'];
const varName = (group, key) => `--${P}-${FLAT.has(group) ? key : `${group}-${key}`}`;

// ---------- tokens.css ----------
const themeBlock = (theme) =>
  entries(T.color).map(([k, v]) => `    --${P}-${k}: ${refCss(v[theme])};`).join('\n');

let tokensCss = `@layer ${P === 'pm' ? 'poiema' : P}.tokens {\n  :root {\n`;
tokensCss += entries(T.primitives).map(([k, v]) => `    --${P}-${k}: ${v};`).join('\n') + '\n\n';
for (const g of SCALES) {
  tokensCss += entries(T[g]).map(([k, v]) => `    ${varName(g, k)}: ${val(v)};`).join('\n') + '\n';
}
tokensCss += `    --${P}-font: var(--${P}-font-sans);\n  }\n\n`;
tokensCss += `  :root, [data-theme="light"], [data-theme="auto"] {\n    color-scheme: light;\n${themeBlock('light')}\n  }\n\n`;
tokensCss += `  [data-theme="dark"] {\n    color-scheme: dark;\n${themeBlock('dark')}\n  }\n\n`;
tokensCss += `  @media (prefers-color-scheme: dark) {\n    [data-theme="auto"] {\n      color-scheme: dark;\n${themeBlock('dark').replace(/^/gm, '  ')}\n    }\n  }\n\n`;
tokensCss += `  @media (max-width: ${T.breakpoint.sm}) {\n    :root { --${P}-text-base: ${T.text.md}; }\n  }\n}\n`;

// ---------- poiema.css bundle ----------
const CSS_ORDER = ['base', 'type', 'layout', 'components', 'forms', 'motion', 'utilities'];
const layerOrder = '@layer poiema.tokens, poiema.base, poiema.components, poiema.utilities;\n';
const bundle = banner + layerOrder + '\n' + tokensCss + '\n' +
  CSS_ORDER.map((f) => read(`src/css/${f}.css`).trim()).join('\n\n') + '\n';

// Conservative minifier for our own CSS: strip comments, collapse whitespace,
// trim around punctuation that never needs surrounding spaces. Leaves +/- alone (calc).
const minify = (css) => css
  .replace(/\/\*(?!!)[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{};,>])\s*/g, '$1')
  .replace(/;}/g, '}')
  .trim() + '\n';

// ---------- tailwind.css (Tailwind CSS v4) ----------
const twColors = entries(T.color)
  .filter(([k]) => !/^(icon-|pillar|card$|card-edge|glass|scrim|inverse-)/.test(k))
  .map(([k]) => `  --color-${k}: var(--${P}-${k});`);
const twPrims = entries(T.primitives).map(([k]) => `  --color-${k}: var(--${P}-${k});`);
const twText = [
  ['eyebrow', `var(--${P}-text-xs)`, '1.4', `var(--${P}-tracking-eyebrow)`, '700'],
  ['lead', `var(--${P}-text-lead)`, `var(--${P}-leading-body)`, null, null],
  ['h4', `var(--${P}-text-h4)`, `var(--${P}-leading-title)`, `var(--${P}-tracking-title)`, '800'],
  ['h3', `var(--${P}-text-h3)`, `var(--${P}-leading-statement)`, `var(--${P}-tracking-title)`, '700'],
  ['h2', `var(--${P}-text-h2)`, `var(--${P}-leading-heading)`, `var(--${P}-tracking-heading)`, '800'],
  ['h1', `var(--${P}-text-h1)`, `var(--${P}-leading-display)`, `var(--${P}-tracking-heading)`, '800'],
  ['display', `var(--${P}-text-display)`, `var(--${P}-leading-display)`, `var(--${P}-tracking-display)`, '800'],
  ['numeral', `var(--${P}-text-numeral)`, `var(--${P}-leading-numeral)`, `var(--${P}-tracking-numeral)`, '900'],
].map(([n, size, lh, ls, fw]) => [
  `  --text-${n}: ${size};`,
  `  --text-${n}--line-height: ${lh};`,
  ls && `  --text-${n}--letter-spacing: ${ls};`,
  fw && `  --text-${n}--font-weight: ${fw};`,
].filter(Boolean).join('\n'));

const tailwind = `${banner}/*
  Poiema × Tailwind CSS v4. Usage (in your main CSS file):

    @layer theme, base, poiema, components, utilities;
    @import "tailwindcss";
    @import "poiema-ui/tailwind.css";
    @import "poiema-ui/poiema.css";   (optional: the pm-* component classes)

  The first line puts Poiema's layer below Tailwind utilities, so utilities always win.
  Tailwind's default color palette is removed on purpose (the system is monochrome);
  delete the "--color-*: initial" line below if you really need it back.
*/
@import "./tokens.css";

@theme {
  --color-*: initial;
}

@theme inline {
  --color-white: #ffffff;
  --color-black: #000000;
  --color-transparent: transparent;
  --color-current: currentColor;
${twColors.join('\n')}
${twPrims.join('\n')}

  --font-sans: var(--${P}-font-sans);
  --font-mono: var(--${P}-font-mono);

${twText.join('\n')}

  --tracking-eyebrow: var(--${P}-tracking-eyebrow);
  --tracking-title: var(--${P}-tracking-title);
  --tracking-heading: var(--${P}-tracking-heading);
  --tracking-display: var(--${P}-tracking-display);
  --leading-display: var(--${P}-leading-display);
  --leading-heading: var(--${P}-leading-heading);

  --radius-card: var(--${P}-radius-xl);
  --radius-callout: var(--${P}-radius-lg);
  --radius-tile: var(--${P}-radius-md);
  --radius-frame: var(--${P}-radius-sm);

  --shadow-lift: var(--${P}-shadow-lift);
  --shadow-float: var(--${P}-shadow-float);
  --drop-shadow-object: var(--${P}-shadow-object);

  --container-page: var(--${P}-container);
  --spacing-gutter: var(--${P}-gutter);
  --spacing-section: var(--${P}-section);
  --spacing-card: var(--${P}-card-pad);

  --ease-settle: var(--${P}-ease);
  --animate-float: pm-float var(--${P}-float-duration) ease-in-out infinite;
  --animate-marquee: pm-marquee var(--${P}-marquee-duration) linear infinite;

  @keyframes pm-float { 0%, 100% { translate: 0 0; } 50% { translate: 0 var(--${P}-float-distance); } }
  @keyframes pm-marquee { to { transform: translateX(-50%); } }
}
`;

// ---------- JS ----------
const js = read('src/js/poiema.js');
const exportNames = [...js.matchAll(/^export (?:async )?(?:function|const|let) (\w+)/gm)].map((m) => m[1]);
const auto = `${banner.replace('/*!', '/*! classic-script build —')}(function () {\n'use strict';\n` +
  js.replace(/^export (async )?(function|const|let) /gm, '$1$2 ') +
  `\nwindow.Poiema = { ${exportNames.join(', ')} };\n` +
  `if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { init(); });\nelse init();\n})();\n`;

// ---------- tokens.js / d.ts / json ----------
const resolved = {
  prefix: P,
  primitives: Object.fromEntries(entries(T.primitives)),
  color: {
    light: Object.fromEntries(entries(T.color).map(([k, v]) => [k, refRaw(v.light)])),
    dark: Object.fromEntries(entries(T.color).map(([k, v]) => [k, refRaw(v.dark)])),
  },
  ...Object.fromEntries([...SCALES, 'breakpoint'].map((g) => [g, Object.fromEntries(entries(T[g]).map(([k, v]) => [k, val(v)]))])),
};
const tokensJs = `${banner}export const tokens = ${JSON.stringify(resolved, null, 2)};\n\n` +
  `/** CSS variable reference for a token, e.g. cssVar('ink') -> "var(--${P}-ink)". */\n` +
  `export const cssVar = (name) => \`var(--${P}-\${name})\`;\n\nexport default tokens;\n`;
const typeOf = (o, ind = '  ') => typeof o === 'object'
  ? `{\n${Object.entries(o).map(([k, v]) => `${ind}${JSON.stringify(k)}: ${typeOf(v, ind + '  ')};`).join('\n')}\n${ind.slice(2)}}`
  : 'string';
const tokensDts = `${banner}export declare const tokens: ${typeOf(resolved)};\nexport declare const cssVar: (name: string) => string;\nexport default tokens;\n`;

// ---------- contrast ----------
const hexRgb = (h) => { h = h.replace('#', ''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255); };
const lum = (h) => { const [R, G, B] = hexRgb(h).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * R + 0.7152 * G + 0.0722 * B; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
const failures = [];
let table = '| Foreground | Background | Light | Dark | Needs |\n|---|---|---|---|---|\n';
for (const [fg, bg, min] of T.contrast.checks) {
  const cells = ['light', 'dark'].map((t) => {
    const x = ratio(resolved.color[t][fg], resolved.color[t][bg]);
    if (x < min) failures.push(`${t}: ${fg} on ${bg} = ${x.toFixed(2)} (< ${min})`);
    return `${x.toFixed(2)}${x < min ? ' ✗' : ''}`;
  });
  table += `| \`${fg}\` | \`${bg}\` | ${cells[0]} | ${cells[1]} | ${min === 3 ? '3 (large text)' : '4.5 (AA)'} |\n`;
}
if (failures.length) { console.error('Contrast failures:\n  ' + failures.join('\n  ')); process.exit(1); }
const replaceBetween = (file, tag, content) => {
  const src = read(file);
  const re = new RegExp(`(<!-- ${tag}:start -->)[\\s\\S]*?(<!-- ${tag}:end -->)`);
  if (!re.test(src)) throw new Error(`Missing <!-- ${tag}:start/end --> markers in ${file}`);
  write(file, src.replace(re, `$1\n${content}\n$2`));
};

// ---------- docs/tokens.md ----------
let tokensMd = `# Token reference\n\n> Generated from \`src/tokens.json\` by \`npm run build\`. Do not edit by hand.\n\n` +
  `Every token is a CSS custom property. Use semantic colors (\`--${P}-ink\`, \`--${P}-canvas\`…), never primitives, in components.\n\n` +
  `## Semantic colors\n\n| Variable | Light | Dark | Use |\n|---|---|---|---|\n`;
for (const [k, v] of entries(T.color)) {
  if (k.startsWith('icon-')) { tokensMd += `| \`--${P}-${k}\` | *(svg)* | *(svg)* | ${v.description} |\n`; continue; }
  tokensMd += `| \`--${P}-${k}\` | \`${refRaw(v.light)}\` | \`${refRaw(v.dark)}\` | ${v.description} |\n`;
}
tokensMd += `\n## Primitives\n\n${T.primitives.$description}\n\n| Variable | Value |\n|---|---|\n` +
  entries(T.primitives).map(([k, v]) => `| \`--${P}-${k}\` | \`${v}\` |`).join('\n') + '\n';
for (const g of SCALES) {
  tokensMd += `\n## ${g[0].toUpperCase() + g.slice(1)}\n\n${T[g].$description ? T[g].$description + '\n\n' : ''}| Variable | Value | Note |\n|---|---|---|\n` +
    entries(T[g]).map(([k, v]) => `| \`${varName(g, k)}\` | \`${val(v)}\` | ${desc(v)} |`).join('\n') + '\n';
}
tokensMd += `\n## Breakpoints\n\n${T.breakpoint.$description}\n\n| Name | Value |\n|---|---|\n` +
  entries(T.breakpoint).map(([k, v]) => `| ${k} | \`max-width: ${v}\` |`).join('\n') + '\n';

// ---------- write dist ----------
rmSync(r('dist'), { recursive: true, force: true });
write('dist/tokens.css', banner + tokensCss);
write('dist/poiema.css', bundle);
write('dist/poiema.min.css', banner + minify(bundle.slice(banner.length)));
write('dist/tailwind.css', tailwind);
write('dist/fonts.css', `${banner}@import url("https://fonts.googleapis.com/css2?family=Inter+Tight:wght@400;500;600;700;800;900&display=swap");\n`);
write('dist/poiema.js', banner + js);
write('dist/poiema.auto.js', auto);
write('dist/poiema.d.ts', banner + read('src/js/poiema.d.ts'));
write('dist/tokens.js', tokensJs);
write('dist/tokens.d.ts', tokensDts);
write('dist/tokens.json', JSON.stringify(resolved, null, 2) + '\n');
mkdirSync(r('dist/assets'), { recursive: true });
for (const f of readdirSync(r('assets'))) copyFileSync(r('assets', f), r('dist/assets', f));

// ---------- docs, skills, llms ----------
write('docs/tokens.md', tokensMd);
replaceBetween('docs/color.md', 'contrast', table.trim());

const DOCS = ['principles', 'voice', 'color', 'typography', 'layout', 'motion', 'components', 'imagery', 'frameworks', 'tokens'];
const SKILL_REFS = {
  'poiema-design': ['principles', 'color', 'typography', 'layout', 'motion', 'components', 'imagery', 'frameworks', 'tokens'],
  'poiema-voice': ['voice', 'principles'],
  'poiema-review': ['principles', 'voice', 'color', 'typography', 'motion', 'components'],
};
for (const [skill, docs] of Object.entries(SKILL_REFS)) {
  rmSync(r(`skills/${skill}/references`), { recursive: true, force: true });
  for (const d of docs) {
    write(`skills/${skill}/references/${d}.md`, `<!-- Copied from docs/${d}.md by npm run build. Edit the original. -->\n\n` + read(`docs/${d}.md`));
  }
}
write('llms-full.txt', [`# ${pkg.name} — full context\n\n${pkg.description}\n`, read('AGENTS.md'), ...DOCS.map((d) => read(`docs/${d}.md`))].join('\n\n---\n\n'));

const size = (p) => (readFileSync(r(p)).length / 1024).toFixed(1) + ' kB';
console.log(`built ${pkg.name}@${pkg.version}
  dist/poiema.css      ${size('dist/poiema.css')}  (min ${size('dist/poiema.min.css')})
  dist/poiema.js       ${size('dist/poiema.js')}  exports: ${exportNames.join(', ')}
  dist/tailwind.css    ${size('dist/tailwind.css')}
  contrast             ${T.contrast.checks.length * 2} pairs pass`);
if (!existsSync(r('dist/assets/gem.svg'))) console.warn('warning: dist/assets/gem.svg missing');
